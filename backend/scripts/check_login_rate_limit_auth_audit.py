#!/usr/bin/env python3
"""Static guard for v0.41.1 Step 6 Login Rate Limit / Auth Audit."""
from pathlib import Path
import re, sys
ROOT=Path(__file__).resolve().parents[2]
checks=[]
def read(p): return (ROOT/p).read_text()
def check(name, ok, detail=''): checks.append((name,bool(ok),detail))

config=read('backend/internal/config/config.go')
config_test=read('backend/internal/config/config_test.go')
auth=read('backend/internal/api/auth.go')
limiter=read('backend/internal/api/login_rate_limit.go')
limiter_test=read('backend/internal/api/login_rate_limit_test.go')
trace=read('backend/internal/api/traceability.go')
router=read('backend/internal/api/router.go')
main=read('backend/cmd/server/main.go')
openapi=read('backend/internal/api/openapi.json')
compose=read('docker-compose.yml')
prod=read('docker-compose.prod.yml')
ci=read('.github/workflows/ci.yml')
make=read('Makefile')
e2e=read('e2e/tests/auth-rate-limit-audit.spec.ts')
doc=read('docs/LOGIN_RATE_LIMIT_AUTH_AUDIT.md')
mig4=read('backend/migrations/0004_traceability_audit.sql')

check('IP limiter config modeled', 'LoginRateLimitIPMaxFailures' in config)
check('username limiter config modeled', 'LoginRateLimitUsernameMaxFailures' in config)
check('rate window config modeled', 'LoginRateLimitWindow' in config)
check('IP default is positive', 'DefaultLoginRateLimitIPMaxFailures       = 30' in config)
check('username default is positive', 'DefaultLoginRateLimitUsernameMaxFailures = 5' in config)
check('window default is 15m', 'DefaultLoginRateLimitWindow              = 15 * time.Minute' in config)
check('invalid positive int rejected', 'func getPositiveInt' in config)
check('invalid positive duration rejected', 'func getPositiveDuration' in config)
check('config unit tests rate defaults', 'TestLoadLoginRateLimitDefaults' in config_test)
check('config unit tests explicit limits', 'TestLoadAcceptsExplicitLoginRateLimit' in config_test)
check('config unit tests invalid limits', 'TestLoadRejectsInvalidLoginRateLimit' in config_test)

check('separate IP map', bool(re.search(r'\bip\s+map\[string\]loginFailureBucket', limiter)))
check('separate username map', bool(re.search(r'\busername\s+map\[string\]loginFailureBucket', limiter)))
check('username normalization', 'strings.ToLower(strings.TrimSpace(username))' in limiter)
check('pre-auth limiter check', 'h.loginLimiter.Check(ip, body.Username)' in auth)
check('invalid credentials increment failures', 'h.loginLimiter.RecordFailure(ip, body.Username)' in auth)
check('success resets username only', 'h.loginLimiter.RecordSuccess(res.Username)' in auth and 'delete(l.username, key)' in limiter)
check('success does not delete IP bucket', 'delete(l.ip' not in limiter)
check('429 is emitted', 'http.StatusTooManyRequests' in auth)
check('Retry-After is emitted', 'w.Header().Set("Retry-After"' in auth)
check('401 remains generic', 'service.ErrInvalidCredentials' in auth)
check('browser and token share authenticate helper', 'h.authenticateLogin(w, r, "browser")' in auth and 'h.authenticateLogin(w, r, "api-token")' in auth)
check('login request body is bounded', 'http.MaxBytesReader(w, r.Body, maxLoginRequestBytes)' in auth)
check('rate-limit key memory is bounded', 'const maxTrackedLoginKeys = 50000' in limiter and 'len(store) < maxTrackedLoginKeys' in limiter)

for event in ['LOGIN_SUCCESS','LOGIN_FAILURE','LOGIN_THROTTLED','LOGOUT']:
    check(f'audit event {event}', f'"{event}"' in auth)
check('auth resource is explicit', 'Resource:   "authentication"' in trace)
check('auth audit records IP', 'IPAddress:  clientIP(r)' in trace)
check('auth audit records request ID', 'details["requestId"]' in trace)
check('auth generic body audit skipped', 'strings.HasPrefix(r.URL.Path, "/api/auth/")' in trace)
check('auth audit payload does not include password', '"password"' not in trace.lower())
check('auth audit payload does not include JWT', 'sessionToken' not in trace and 'Authorization' not in trace)
check('existing audit_log reused', 'CREATE TABLE IF NOT EXISTS audit_log' in mig4)
check('X-Real-IP used', 'r.Header.Get("X-Real-IP")' in trace)
check('X-Forwarded-For ignored by clientIP', 'Header.Get("X-Forwarded-For")' not in trace[trace.index('func clientIP'):trace.index('func recordAuthAudit')])

check('router carries limiter window', 'LoginRateLimitWindow' in router)
check('router constructs limiter', 'newLoginRateLimiter' in router)
check('main passes limiter window', 'LoginRateLimitWindow:              cfg.LoginRateLimitWindow' in main)
check('main passes IP max', 'LoginRateLimitIPMaxFailures:       cfg.LoginRateLimitIPMaxFailures' in main)
check('main passes username max', 'LoginRateLimitUsernameMaxFailures: cfg.LoginRateLimitUsernameMaxFailures' in main)
check('compose exposes limiter env', 'LOGIN_RATE_LIMIT_IP_MAX_FAILURES' in compose and 'LOGIN_RATE_LIMIT_USERNAME_MAX_FAILURES' in compose)
check('production compose exposes limiter env', 'LOGIN_RATE_LIMIT_WINDOW' in prod)
check('OpenAPI documents 429', openapi.count('"429"') >= 2 and 'Retry-After' in openapi)
check('limiter unit tests independent buckets', 'TestLoginRateLimiterUsesIndependentUsernameAndIPBuckets' in limiter_test)
check('limiter unit tests success reset semantics', 'TestLoginRateLimiterSuccessResetsUsernameButNotIP' in limiter_test)
check('limiter unit tests expiry', 'TestLoginRateLimiterWindowExpires' in limiter_test)
check('E2E verifies 429', 'expect(last.status()).toBe(429)' in e2e)
check('E2E verifies Retry-After', "last.headers()['retry-after']" in e2e)
check('E2E verifies audit actions', 'LOGIN_THROTTLED' in e2e and 'LOGIN_FAILURE' in e2e and 'LOGIN_SUCCESS' in e2e and 'LOGOUT' in e2e)
check('Step6 guard in CI', 'check_login_rate_limit_auth_audit.py' in ci)
check('Step6 guard in Makefile', 'check-login-security' in make)
check('Step6 documentation exists', 'Login Rate Limit / Authentication Audit' in doc)

migs=sorted((ROOT/'backend/migrations').glob('*.sql'))
vers=[int(m.name[:4]) for m in migs if re.match(r'^\d{4}_',m.name)]
check('migration count is 43', len(vers)==43, f'count={len(vers)}')
check('latest migration is 0043', bool(vers) and max(vers)==43, f'latest={max(vers) if vers else None}')
check('migration 0043 present', any(v==43 for v in vers) and not any(v>43 for v in vers))
failed=[x for x in checks if not x[1]]
for n,ok,d in checks:
    print(('PASS' if ok else 'FAIL')+': '+n+(f' ({d})' if d else ''))
print(f'\nLogin rate limit/auth audit static guard: {len(checks)-len(failed)}/{len(checks)} PASS')
if failed: sys.exit(1)
