#!/usr/bin/env python3
"""Static guard for v0.41.1 Step 5 Cookie Auth / CORS / CSRF."""
from pathlib import Path
import re, sys
ROOT=Path(__file__).resolve().parents[2]
checks=[]
def read(p): return (ROOT/p).read_text()
def check(name, ok, detail=''): checks.append((name,bool(ok),detail))

auth=read('backend/internal/api/auth.go')
cookies=read('backend/internal/api/auth_cookies.go')
svc=read('backend/internal/service/auth.go')
router=read('backend/internal/api/router.go')
main=read('backend/cmd/server/main.go')
config=read('backend/internal/config/config.go')
frontend=read('frontend/src/api/index.ts')
store=read('frontend/src/stores/auth.ts')
router_ts=read('frontend/src/router/index.ts')
openapi=read('backend/internal/api/openapi.json')
ci=read('.github/workflows/ci.yml')
e2e=read('e2e/tests/auth-cookie-csrf.spec.ts')
doc=read('docs/COOKIE_AUTH_CORS_CSRF.md')

check('browser login does not serialize JWT', '"token": res.Token' not in auth and 'writeJSON(w, http.StatusOK, map[string]any{' in auth)
check('explicit bearer token endpoint exists', 'api.Post("/auth/token", srv.tokenLogin)' in router)
check('browser logout endpoint exists', 'secured.Post("/auth/logout", srv.logout)' in router)
check('auth middleware accepts cookie fallback', 'r.Cookie(cookies.sessionName())' in auth)
check('bearer remains supported', 'authSourceBearer' in auth and 'Authorization' in auth)
check('session JWT cookie is HttpOnly', 'HttpOnly: true' in cookies)
check('production session uses __Host prefix', '__Host-cpim-session' in cookies)
check('production csrf uses __Host prefix', '__Host-cpim-csrf' in cookies)
check('cookies have Path root', 'Path:     "/"' in cookies)
check('cookie secure flag is configurable', 'Secure:   c.secure' in cookies)
check('cookie sameSite is configurable', 'SameSite: c.sameSite' in cookies)
check('logout expires cookies', 'MaxAge:   -1' in cookies)
check('CSRF random nonce uses crypto/rand', '"crypto/rand"' in svc and 'rand.Read' in svc)
check('CSRF uses HMAC SHA256', 'hmac.New(sha256.New' in svc)
check('CSRF is session bound', 's.csrfMAC(sessionToken' in svc)
check('CSRF compares header and cookie constant time', 'subtle.ConstantTimeCompare' in auth)
check('unsafe cookie requests validate CSRF signature', 'VerifyCSRFToken(sessionToken, header)' in auth)
check('cross-site Fetch Metadata rejected', 'Sec-Fetch-Site' in auth and 'cross-site' in auth)
check('Origin validation exists', 'trustedBrowserOrigin' in auth and 'sameRequestOrigin' in cookies)
check('Bearer skips browser CSRF', 'ctxKeyAuthSource) != authSourceCookie' in auth)
check('CORS credentials enabled', 'AllowCredentials: true' in router)
check('CORS permits CSRF header', 'csrfHeaderName' in router and 'AllowedHeaders' in router)
check('CORS has no wildcard default', 'defaultDevAllowedOrigins' in config and 'allowedOriginsDefault := defaultDevAllowedOrigins' in config)
check('wildcard origin rejected globally', 'must not contain wildcard; credentialed CORS requires explicit origins' in config)
check('main passes cookie secure config', bool(re.search(r'CookieSecure\s*:\s*cfg\.CookieSecure', main)))
check('main passes cookie sameSite config', bool(re.search(r'CookieSameSite\s*:\s*cfg\.CookieSameSite', main)))
check('SPA axios uses credentials', 'withCredentials: true' in frontend)
check('SPA adds CSRF header', "const CSRF_HEADER = 'X-CSRF-Token'" in frontend)
check('SPA reads only CSRF cookies', "readCookie('__Host-cpim-csrf')" in frontend and "readCookie('cpim-csrf')" in frontend)
check('SPA has no localStorage auth use', 'localStorage' not in frontend and 'localStorage' not in store)
check('SPA has no JWT Authorization injection', 'Bearer ${' not in frontend and 'cpim.token' not in frontend and 'cpim.token' not in store)
check('SPA restores session with auth/me', "http.get<SessionUser>('/auth/me')" in store)
check('SPA logout calls server', "http.post('/auth/logout'" in store)
check('router awaits auth initialization', 'await auth.initialize()' in router_ts)
check('OpenAPI declares cookie auth', '"cookieAuth"' in openapi and '__Host-cpim-session' in openapi)
check('OpenAPI documents bearer token endpoint', '"/auth/token"' in openapi)
check('OpenAPI documents logout', '"/auth/logout"' in openapi)
check('browser E2E checks HttpOnly', 'session?.httpOnly' in e2e)
check('browser E2E checks Secure', 'session?.secure' in e2e)
check('browser E2E checks no localStorage token', "localStorage.getItem('cpim.token')" in e2e)
check('browser E2E checks CSRF rejection', 'expect(noCSRF.status()).toBe(403)' in e2e)
check('browser E2E checks bearer compatibility', "request.post('/api/auth/token'" in e2e)
check('Step5 guard in CI', 'check_cookie_auth_csrf.py' in ci)
check('Step5 documentation exists', 'signed double-submit' in doc)

migs=sorted((ROOT/'backend/migrations').glob('*.sql'))
vers=[int(m.name[:4]) for m in migs if re.match(r'^\d{4}_',m.name)]
check('migration count is 45', len(vers)==45, f'count={len(vers)}')
check('latest migration is 0045', bool(vers) and max(vers)==45, f'latest={max(vers) if vers else None}')
check('migration 0045 present', any(v==45 for v in vers) and not any(v>45 for v in vers))
failed=[x for x in checks if not x[1]]
for n,ok,d in checks:
    print(('PASS' if ok else 'FAIL')+': '+n+(f' ({d})' if d else ''))
print(f'\nCookie auth/CORS/CSRF static guard: {len(checks)-len(failed)}/{len(checks)} PASS')
if failed: sys.exit(1)
